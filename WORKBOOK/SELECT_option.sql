-- 문제 18
SELECT STUDENT_NO, STUDENT_NAME
FROM(
	SELECT ts.STUDENT_NO, STUDENT_NAME, AVG(POINT) 
	FROM TB_STUDENT ts 
	JOIN TB_DEPARTMENT td ON(ts.DEPARTMENT_NO = td.DEPARTMENT_NO)
	JOIN TB_GRADE tg ON(ts.STUDENT_NO = tg.STUDENT_NO)
	WHERE DEPARTMENT_NAME = '국어국문학과'
	GROUP BY ts.STUDENT_NO, STUDENT_NAME
	ORDER BY 3 DESC)
WHERE ROWNUM =1;

-- 문제 19
SELECT DEPARTMENT_NAME "계열학과명", ROUND(AVG(POINT), 1) "전공평점"
FROM TB_DEPARTMENT td
JOIN TB_CLASS tc ON(td.DEPARTMENT_NO = tc.DEPARTMENT_NO)
JOIN TB_GRADE tg ON(tc.CLASS_NO = tg.CLASS_NO)
WHERE CATEGORY = (SELECT CATEGORY FROM TB_DEPARTMENT WHERE DEPARTMENT_NAME = '환경조경학과')
AND CLASS_TYPE LIKE '전공%'
GROUP BY DEPARTMENT_NAME
ORDER BY 1;


















