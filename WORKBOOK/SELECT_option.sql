-- 문제 15
SELECT ts.STUDENT_NO "학번", ts.STUDENT_NAME "이름", td.DEPARTMENT_NAME "학과 이름", AVG(POINT)
FROM TB_STUDENT ts
JOIN TB_DEPARTMENT td ON(ts.DEPARTMENT_NO = td.DEPARTMENT_NO)
JOIN TB_GRADE tg ON(ts.STUDENT_NO = tg.STUDENT_NO)
WHERE ABSENCE_YN != 'Y'
GROUP BY ts.STUDENT_NO, ts.STUDENT_NAME, td.DEPARTMENT_NAME
HAVING AVG(POINT) >= 4.0
ORDER BY 1;

-- 문제 16
SELECT tc.CLASS_NO, CLASS_NAME, AVG(POINT)
FROM TB_CLASS tc 
JOIN TB_DEPARTMENT td ON(tc.DEPARTMENT_NO = td.DEPARTMENT_NO)
JOIN TB_GRADE tg ON(tc.CLASS_NO = tg.CLASS_NO)
WHERE CLASS_TYPE LIKE '전공%'
AND DEPARTMENT_NAME = '환경조경학과'
GROUP BY tc.CLASS_NO, CLASS_NAME
ORDER BY 1;

